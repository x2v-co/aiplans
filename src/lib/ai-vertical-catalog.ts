export type AiCatalogKind = 'agent' | 'creative-plan' | 'video-model' | 'music-model' | 'world-model' | 'decision-model' | 'voice-model' | 'image-model';

export type AiCatalogStatus = 'available' | 'waitlist' | 'preview' | 'research' | 'announced' | 'discontinued' | 'needs-verification' | 'deprecated';
export type AiCatalogModality = 'text' | 'image' | 'video' | 'audio' | 'music' | '3d' | 'simulation' | 'code' | 'robotics';
export type AiCatalogAccess = 'consumer-app' | 'api' | 'cloud-api' | 'open-weights' | 'research-preview' | 'enterprise' | 'waitlist';
export type AiPricingConfidence = 'verified' | 'unit-only' | 'unknown' | 'not-commercial';
export type AiModelCategory = 'video' | 'music' | 'world' | 'decision' | 'speech' | 'image';

export interface AiCatalogSource {
  label: string;
  url: string;
  publisher: string;
}

export interface AiBenchmarkSummary {
  benchmarkSlug: string;
  benchmarkName: string;
  taskName: string;
  metricName: string;
  unit: string | null;
  value: number;
  officialUrl: string | null;
}

export interface AiCatalogItem {
  kind: AiCatalogKind;
  slug?: string;
  name: string;
  provider: string;
  providerSlug?: string;
  providerLogoUrl?: string;
  status: AiCatalogStatus;
  pricing: string;
  unit: string;
  capabilities: string[];
  bestFor: string;
  url?: string;

  /** Optional SRE seed; DB drift remains a warning during rollout. */
  deferredDbSeed?: boolean;
  /** npm script that writes a deferredDbSeed row; defaults to seed:non-llm-2026-10-15:apply. */
  deferredDbSeedScript?: string;
  releasedAt?: string;
  deprecatedAt?: string;
  shutdownDate?: string;
  replacementModel?: string;
  deprecationSourceUrl?: string;
  pricingProviderSlug?: string;
  pricingChannel?: string;
  usageRates?: { priceKind: string; unit: string; price: number; approximate?: boolean }[];

  /** Model-category metadata; unknown world-model specifications remain unset. */
  modelCategory?: AiModelCategory;
  inputModalities?: AiCatalogModality[];
  outputModalities?: AiCatalogModality[];
  access?: AiCatalogAccess[];
  pricingUnit?: string;
  pricingConfidence?: AiPricingConfidence;
  sourceUrls?: AiCatalogSource[];
  lastVerified?: string;
  notes?: string;
  benchmarkSummaries?: AiBenchmarkSummary[];
  billingUnit?: 'per_second' | 'per_world' | 'per_token' | 'subscription_included' | 'contract' | 'open_source_self_host' | 'per_song';
  pricePerUnit?: number | null;
  pricePerUnitHigh?: number;
  approximatePrice?: boolean;
  inputPricePer1M?: number | null;
  outputPricePer1M?: number | null;
  pricePer1MTasks?: number | null;
  contextWindowLabel?: string;
  contextWindow?: number;
  currency?: string;
  resolutionTier?: string;
  fps?: number;
  realtime?: boolean;
  maxSessionLen?: string;
  memoryHorizon?: string;
  outputType?: ('video_stream' | '3d_asset' | 'panorama')[];
  accessNote?: string;
  license?: string;
  selfHostHw?: string;
  priceStatus?: 'priced' | 'subscription_included' | 'undisclosed' | 'not_applicable' | 'needs-verification' | 'not-public';
  costPerMinute?: number;
  verifiedAt?: string;
  needsVerification?: string[];
  planTiers?: { name: string; price: number; currency: string; credits?: number; note?: string }[];
}

